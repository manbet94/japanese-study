function toWords(level: Level, groups: Group[]): Word[] {
  return groups.flatMap(([pos, rows]) =>
    rows.map(([word, reading, meaning, example, exampleKo]) => ({
      id: `${level}:${word}`,
      level,
      pos,
      word,
      reading,
      meaning,
      example,
      exampleKo,
    })),
  )
}

export const allWords: Word[] = [...toWords('N5', n5), ...toWords('N4', n4)]

export const wordById: Map<string, Word> = new Map(allWords.map((w) => [w.id, w]))

